/** Sine of a 0..255 phase index, in thousandths. */
export function sin256(i: number): number {
  return SINE_256[((i % 256) + 256) % 256];
}

/** Triangle wave over a 0..255 phase index, in thousandths: 0 → 1000 → 0 → -1000 → 0. */
export function tri256(i: number): number {
  const p = ((i % 256) + 256) % 256;
  if (p < 64) return Math.trunc(p * 1000 / 64);
  if (p < 192) return Math.trunc((128 - p) * 1000 / 64);
  return Math.trunc((p - 256) * 1000 / 64);
}
