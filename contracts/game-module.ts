// ---------------------------------------------------------------------------
// SEEDED PRNG
// ---------------------------------------------------------------------------

/**
 * A seeded pseudo-random number generator returning values in [0, 1).
 *
 * The runtime initializes this from RoundConfig.seed and passes it to the
 * game via RoundConfig.prng. Games MUST use this for all randomness.
 * Calling Math.random() directly violates the determinism contract.
 */
export type SeededPRNG = () => number;

// ---------------------------------------------------------------------------
// ENUMS
// ---------------------------------------------------------------------------

/**
 * Primary interaction modality. Used for UI hints, accessibility labels,
 * and controller mapping. Declare the one that dominates player interaction.
 */
export type ControlScheme = 'tap' | 'hold' | 'swipe' | 'tilt' | 'drag' | 'rhythm';

/**
 * How difficulty evolves over the round duration.
 *   flat  — constant throughout
 *   ramp  — linearly increasing
 *   spike — sudden step increase at one or more points
 */
export type DifficultyCurve = 'flat' | 'ramp' | 'spike';

/**
 * Who or what produced this module.
 *   human  — hand-authored
 *   agent  — fully generated by the Game Factory
 *   reskin — agent-generated variation of a human or agent parent
 */
export type GeneratedBy = 'human' | 'agent' | 'reskin';

// ---------------------------------------------------------------------------
// GAME META
// ---------------------------------------------------------------------------

/**
 * Immutable metadata baked into the module at authoring time.
 * Frozen before the module enters the pool. A change to any field
 * requires a new slug (treat as a new game for ranking purposes).
 */
export interface GameMeta {
  /** UUID v4 assigned at creation. Never reused across the pool. */
  readonly id: string;

  /** URL-safe kebab-case identifier, globally unique in the pool. */
  readonly slug: string;

  /** Human-readable display name. Max 40 characters. */
  readonly title: string;

  /** Primary interaction modality. */
  readonly controlScheme: ControlScheme;

  /**
   * Target round length in seconds. Must be in [25, 60].
   * The runtime may stop a round early (player quit / connectivity loss)
   * but never extends it beyond this value.
   */
  readonly durationSeconds: number;

  /** How difficulty evolves. */
  readonly difficultyCurve: DifficultyCurve;

  /**
   * Free-form classification tags (e.g. ['reflex', 'precision', 'memory']).
   * Used by the Factory for thematic mixing; no semantic contract beyond that.
   * At least one tag required.
   */
  readonly themeTags: readonly string[];

  /** Origin of this module. */
  readonly generatedBy: GeneratedBy;

  /**
   * Slug of the parent module when generatedBy === 'reskin'.
   * Required for reskins; must reference a slug that exists in the pool.
   */
  readonly parentLineage?: string;

  /**
   * Whether a higher rawScore is better (default) or a lower rawScore is
   * better (e.g. time-trial). The normalizer uses this to orient the
   * percentile distribution correctly.
   * @default 'desc'
   */
  readonly scoringDirection?: 'asc' | 'desc';

  /**
   * Declared [min, max] range of rawScore for cold-start normalization.
   * Required. Must reflect the actual achievable range under normal play.
   * See scoring.ts cold-start rule.
   */
  readonly scoringEnvelope: { readonly min: number; readonly max: number };
}

// ---------------------------------------------------------------------------
// ROUND CONFIG
// ---------------------------------------------------------------------------

/**
 * Runtime configuration for a single round instance.
 * Created by the Tournament Runtime and passed to mount().
 * Immutable for the duration of the round.
 */
export interface RoundConfig {
  /**
   * Deterministic integer seed. The runtime derives RoundConfig.prng from
   * this value. Two rounds sharing the same seed and identical input logs
   * MUST produce identical rawScores. See DETERMINISM CONTRACT below.
   */
  readonly seed: number;

  /**
   * Multiplier applied to all time-based speed parameters (obstacle velocity,
   * target decay, timer ticks). 1.0 = design-intent speed.
   * The runtime uses values in [0.5, 2.0] for skill-tier scaling.
   * Games must not apply additional randomness to this value.
   */
  readonly speedMultiplier: number;

  /**
   * Optional palette/asset override for seasonal or venue-specific theming.
   * Purely cosmetic. Games apply this if provided but MUST NOT alter
   * game mechanics, timing, or score paths based on it.
   */
  readonly themeOverride?: string;

  /**
   * Seeded PRNG initialized from `seed` by the runtime.
   * Games MUST use this for every random value they need.
   * Do not call Math.random(). Do not construct your own PRNG.
   * Do not seed a PRNG from Date.now() or any ambient value.
   */
  readonly prng: SeededPRNG;
}

// ---------------------------------------------------------------------------
// GAME EVENT
// ---------------------------------------------------------------------------

/**
 * A single timestamped input event — the atomic unit of the replayable log.
 *
 * The complete ordered sequence of GameEvents from a round, when replayed
 * headlessly against the same seed and RoundConfig, MUST reproduce the
 * identical rawScore. This sequence is the anti-cheat and replay record.
 */
export interface GameEvent {
  /**
   * Milliseconds elapsed since start() was called. Monotonically increasing.
   * Derived from the event's actual occurrence time minus the round start time.
   * Do NOT use Date.now() directly as a score input — only as the basis for
   * computing this relative offset.
   */
  readonly t: number;

  /**
   * Event type. Must match the module's declared controlScheme.
   * Standard values:
   *   tap               — single discrete tap
   *   hold_start        — hold begins
   *   hold_end          — hold ends
   *   swipe_up|down|left|right — directional swipe
   *   drag_start        — drag begins (x, y = start point)
   *   drag_move         — drag in progress (x, y = current point)
   *   drag_end          — drag ends (x, y = release point)
   *   tilt              — device tilt (payload: { alpha, beta, gamma })
   *   beat_hit          — rhythm game on-beat hit
   *   beat_miss         — rhythm game on-beat miss
   */
  readonly type: string;

  /**
   * Normalized [0, 1] x-coordinate of the interaction, relative to the
   * container's left edge. Present for positional events (tap, drag, swipe).
   */
  readonly x?: number;

  /**
   * Normalized [0, 1] y-coordinate of the interaction, relative to the
   * container's top edge. Present for positional events.
   */
  readonly y?: number;

  /**
   * Arbitrary additional payload (e.g. swipe velocity, tilt angles).
   * Must be JSON-serializable. Omit keys with undefined values rather
   * than setting them to null or undefined.
   */
  readonly payload?: Readonly<Record<string, unknown>>;
}

// ---------------------------------------------------------------------------
// ROUND RESULT
// ---------------------------------------------------------------------------

/**
 * The result emitted via the onScore callback at the end of a round.
 *
 * rawScore is game-internal and NOT comparable across different games.
 * Use normalize() from /contracts/scoring.ts for cross-game comparisons.
 * Never expose rawScore in leaderboard UI — always show the percentile.
 */
export interface RoundResult {
  /**
   * The game's internal score for this round. Units and range are
   * game-defined and must be documented in the module's provenance.json.
   * Must be a finite number.
   */
  readonly rawScore: number;

  /**
   * Complete ordered input log for this round. Every GameEvent that
   * influenced the score path must appear here. The runtime stores this
   * for replay verification and anti-cheat audits.
   *
   * Replaying these events against the same RoundConfig.seed MUST yield
   * the same rawScore. Omitting events that affected the score is a
   * contract violation.
   */
  readonly events: readonly GameEvent[];
}

// ---------------------------------------------------------------------------
// DETERMINISM CONTRACT
// ---------------------------------------------------------------------------
//
// Every GameModule MUST be fully deterministic given (seed, events):
//
//   headlessReplay(seed, events) === rawScore   // always, on any device
//
// Rules that guarantee this:
//
//   1. NO Math.random(). All randomness comes from RoundConfig.prng, which
//      the runtime seeds from RoundConfig.seed using a stable algorithm
//      (currently mulberry32). Same seed = same sequence of prng() calls =
//      same random values.
//
//   2. NO time as a randomness source. Date.now() and performance.now()
//      are permitted for computing GameEvent.t (the relative offset), but
//      must never appear in a code path that influences rawScore.
//
//   3. NO external state. localStorage, sessionStorage, network responses,
//      and ambient globals must not influence score paths. Games are hermetic.
//
//   4. SIMULATION-DRIVEN physics. If the game uses a physics or animation
//      engine, it must be driven by GameEvent.t timestamps, not by wall-clock
//      time, so that headless replays are frame-rate-independent and produce
//      the same result regardless of device performance.
//
//   5. VERIFIED BY RUNTIME. After each real round, R1 runs a headless replay.
//      If the replayed score differs from the submitted score, the round is
//      flagged for review and the module is quarantined until resolved.
//
// See /contracts/README.md for the full rationale.

// ---------------------------------------------------------------------------
// GAMEMODULE INTERFACE
// ---------------------------------------------------------------------------

/**
 * The contract every game module must satisfy.
 *
 * Lifecycle (strict order):
 *   mount(container, config)
 *     → onScore(cb)           // register callback before start
 *     → start()               // begin the round
 *     → [cb fires exactly once when round ends]
 *     → destroy()             // always called, even if start() never was
 *
 * A module may be mounted and destroyed many times (the Factory test harness
 * runs 100+ cycles). destroy() MUST be clean every time.
 */
export interface GameModule {
  /** Immutable metadata. Set at module creation time; never mutated. */
  readonly meta: GameMeta;

  /**
   * Attach the game to the DOM and initialize all resources (canvas,
   * audio context, asset loading, initial render).
   *
   * Constraints:
   *   - The game owns `container` for the duration of the mount. It must
   *     not read from or write to any element outside `container`.
   *   - No timers, event listeners, or animation frames may be started
   *     until start() is called.
   *   - Calling mount() twice without an intervening destroy() is a caller
   *     bug; the implementation may throw an Error.
   *   - mount() must be synchronous with respect to DOM attachment.
   *     Asset loading may be async internally, but the game must be
   *     ready to receive start() by the time the runtime calls it
   *     (the runtime awaits a ready signal not specified in this interface —
   *     see R1 for the readiness handshake protocol).
   *
   * @param container - The HTMLElement the game renders into.
   * @param config - Round parameters for this round instance.
   */
  mount(container: HTMLElement, config: RoundConfig): void;

  /**
   * Begin the round.
   *
   * Called exactly once per mount, after onScore() has been registered.
   * After start() returns, the game loop is live. The onScore callback
   * will fire exactly once when the round ends — either at durationSeconds
   * or when the runtime sends an explicit stop signal.
   *
   * The game must not call the onScore callback from within start().
   */
  start(): void;

  /**
   * Register the runtime's result-receiver callback.
   *
   * Must be called before start(). Called at most once per mount.
   * The registered callback must be invoked exactly once per round,
   * after the round ends. Invoking it more than once is a contract violation.
   *
   * @param cb - Receives the RoundResult when the round concludes.
   */
  onScore(cb: (result: RoundResult) => void): void;

  /**
   * Fully tear down the game and release all resources.
   *
   * HARD CONTRACT — after destroy() returns, ALL of the following must hold:
   *
   *   1. Every DOM event listener added during mount/start is removed.
   *   2. Every timer (setTimeout, setInterval, requestAnimationFrame loops)
   *      is cancelled.
   *   3. The container's DOM content is cleared (innerHTML = '' or equivalent
   *      renderer teardown such as renderer.destroy()).
   *   4. All heap references to large objects (PixiJS textures, audio buffers,
   *      WebGL contexts, canvas elements) are released so the GC can collect them.
   *   5. After 100 sequential mount → destroy cycles on the same container
   *      with the same RoundConfig, JS heap growth must be flat (verified by
   *      the Factory test harness using performance.measureUserAgentSpecificMemory).
   *   6. destroy() is idempotent: calling it on an already-destroyed instance
   *      must be a safe no-op (do not throw).
   *   7. destroy() must handle the case where start() was never called
   *      (early teardown during pre-load).
   *
   * The runtime calls destroy() unconditionally at round end, regardless of
   * whether the round completed normally or was aborted.
   */
  destroy(): void;
}
